// Operator reconciliation for the already authorized surplus refund; never changes reward or recipient.
import { readFileSync, writeFileSync } from 'node:fs';
import { Account, actions, teraToGas, type KeyPairString } from 'near-api-js';
import { createPublicClient, http, erc20Abi, type Address } from 'viem';
import { baseSepolia } from 'viem/chains';
import { env, keyFor } from '../server/env.ts';
import { rpcProvider } from '../../../services/relayer/src/near.ts';
import { Monerium } from '../../../services/relayer/src/monerium.ts';
import { Store } from '../../../services/relayer/src/store.ts';
import { shortIban } from '../../../services/relayer/src/logic.ts';
if(env.network!=='testnet'||env.monerium.api!=='https://api.monerium.dev'||env.monerium.chain!=='basesepolia')throw new Error('Sandbox only');
const auditFile=`${env.dataDir}/sandbox/overpayment-recovery-4.json`;
const audit=JSON.parse(readFileSync(auditFile,'utf8'));
if(audit.refundShortIban!=='EE31...4264'||audit.payoutId!==2||!audit.recoveryHash)throw new Error('Confirmed recovery journal mismatch');
const provider=rpcProvider(env.nearRpc);
const view=<T=any>(method:string,args:Record<string,unknown>)=>provider.callFunction({contractId:env.contractId,method,args}) as Promise<T>;
const payout=await view('get_payout',{payout_id:2});const job=await view('get_job',{job_id:4});
if(payout.state!=='Signed'||payout.amount_cents!==audit.refundCents||payout.short_iban!==audit.refundShortIban||payout.monerium_order_id||payout.attempt!==0)throw new Error('Payout changed; manual review required');
if(Date.now()<= (payout.message_unix_secs+300)*1000)throw new Error('Wait until the previous authorization has expired');
const m=new Monerium({moneriumApi:env.monerium.api,moneriumClientId:env.monerium.clientId,moneriumClientSecret:env.monerium.clientSecret,chain:env.monerium.chain} as any);
const owned=(await m.ibans()).filter(i=>shortIban(i.iban)===audit.refundShortIban&&i.chain===env.monerium.chain);
if(owned.length!==1)throw new Error('Confirmed recipient is not a unique owned client IBAN');
const orders=await m.ordersFor(job.escrow_evm_address);
if(orders.some(o=>o.kind==='redeem'&&o.memo==='NearPortal job 4 payout 2'))throw new Error('Existing refund order found; do not retry');
const evm=createPublicClient({chain:baseSepolia,transport:http('https://sepolia.base.org')});
const tokens=await evm.readContract({address:'0x29F37F6adCa168B79B8d9567eab9BE3fBF21db85',abi:erc20Abi,functionName:'balanceOf',args:[job.escrow_evm_address as Address]});
if(tokens!==BigInt(audit.receiptCents)*10n**16n)throw new Error('Escrow balance changed; do not retry');
const store=new Store(`${env.dataDir}/github-relayer.json`);
if(store.state.submitted[2]||!store.state.pendingSubmissions?.[2]||shortIban(store.state.jobs[4]!.client.iban)!==audit.refundShortIban)throw new Error('Local submission state changed');
audit.refundReconciliation={at:new Date().toISOString(),oldAttempt:payout.attempt,expiredMessageUnixSeconds:payout.message_unix_secs,noRemoteOrder:true,escrowBalanceVerified:true};
writeFileSync(auditFile,JSON.stringify(audit,null,2),{mode:0o600});
const mediator=new Account(env.mediator,provider,keyFor(env.mediator) as KeyPairString);
const tx=await mediator.signAndSendTransaction({receiverId:env.contractId,actions:[actions.functionCall('authorize_resign',{payout_id:2},teraToGas('100'),0n),actions.functionCall('retry_payout',{payout_id:2},teraToGas('200'),0n)],waitUntil:'FINAL'});
audit.refundReconciliation.retryHash=tx.transaction.hash;
writeFileSync(auditFile,JSON.stringify(audit,null,2),{mode:0o600});
const after=await view('get_payout',{payout_id:2});
if(after.attempt!==1||after.amount_cents!==payout.amount_cents||after.short_iban!==payout.short_iban)throw new Error('Fresh payout binding mismatch');
// The destination is verified as this profile's own account, not a third-party large payout.
store.state.jobs[4]!.client.own=true;
delete store.state.pendingSubmissions![2];store.save();
console.log(JSON.stringify({payoutId:2,amountCents:after.amount_cents,refundShortIban:after.short_iban,state:after.state,attempt:after.attempt,retryHash:tx.transaction.hash}));
